const assert = require('node:assert/strict');
const { randomBytes } = require('node:crypto');
const { once } = require('node:events');
const fs = require('node:fs');
const http = require('node:http');
const net = require('node:net');
const os = require('node:os');
const path = require('node:path');
const Module = require('node:module');
const { mock } = require('node:test');

const baseUri = 'mongodb://127.0.0.1:27017';
const databasePattern = /^budget_ownership_it_[a-f0-9]{32}$/;
const compiled = filename => path.resolve(__dirname, '../../dist', filename);

function testConfiguration(env) {
  if (env.MONGODB_INTEGRATION_TEST !== '1') {
    throw new Error('MongoDB integration requires MONGODB_INTEGRATION_TEST=1');
  }
  // Exact comparison intentionally rejects credentials, paths, queries, SRV,
  // alternate hosts/ports, encoding tricks and whitespace. No application fallback.
  if (env.MONGODB_TEST_BASE_URI !== baseUri) {
    throw new Error('MONGODB_TEST_BASE_URI must exactly match the test-only loopback allowlist');
  }
  if ([env.DATA_BASE_URL, env.DATA_BASE_URL_LOCAL].includes(baseUri)) {
    throw new Error('Application database configuration must not be reused for integration tests');
  }
  return Object.freeze({ baseUri, databaseName: `budget_ownership_it_${randomBytes(16).toString('hex')}` });
}

function assertOwnedDatabase(connection, databaseName) {
  assert.equal(databasePattern.test(databaseName), true, 'Invalid generated test database name');
  assert.equal(connection.readyState, 1, 'Test database must be connected');
  assert.equal(connection.name, databaseName, 'Connection is not the database generated by this execution');
  assert.equal(connection.db.databaseName, databaseName, 'Active driver database does not match this execution');
}

async function openTestDatabase(mongoose, env) {
  // Validate before even inspecting Mongoose, much less opening a connection.
  const config = testConfiguration(env);
  const connection = mongoose.connection;
  assert.equal(connection.readyState, 0, 'Refusing to reuse an existing Mongoose connection');
  try {
    await mongoose.connect(config.baseUri, {
      dbName: config.databaseName, serverSelectionTimeoutMS: 5000,
      connectTimeoutMS: 5000, socketTimeoutMS: 5000, autoIndex: false, autoCreate: false,
    });
    assertOwnedDatabase(connection, config.databaseName);
  } catch {
    try { await connection.close(true); } catch {
      throw new Error('Test MongoDB connection and connection cleanup failed; details suppressed');
    }
    throw new Error('Test MongoDB was unavailable or failed the ownership guard; connection closed; details suppressed');
  }
  let cleanup;
  return Object.freeze({
    name: config.databaseName,
    connection,
    dispose() {
      if (cleanup) return cleanup;
      cleanup = (async () => {
        try {
          assertOwnedDatabase(connection, config.databaseName);
          await connection.dropDatabase();
          const collections = await connection.db.listCollections({}, { nameOnly: true }).toArray();
          assert.equal(collections.length, 0, 'Owned test database was not cleared');
        } finally {
          await connection.close(true);
        }
        assert.equal(connection.readyState, 0, 'Test database connection did not close');
        return { dropped: true, disconnected: true };
      })();
      return cleanup;
    },
  });
}

async function bounded(promise, label) {
  let timer;
  try {
    return await Promise.race([promise, new Promise((resolve, reject) => {
      timer = setTimeout(() => reject(new Error(`Timed out releasing test resource: ${label}`)), 5000);
    })]);
  } finally { clearTimeout(timer); }
}

async function createHarness(env) {
  // Reject unsafe configuration before loading any application modules or logging.
  testConfiguration(env);
  const mongoose = require('mongoose');
  const database = await openTestDatabase(mongoose, env);
  const originalCwd = process.cwd();
  const names = ['NODE_ENV', 'JWT_SECRET', 'DEFAULT_ALLOWED_METHODS'];
  const savedEnv = Object.fromEntries(names.map(name => [name, process.env[name]]));
  const loggers = [];
  const opened = [];
  const fileClosures = [];
  const streams = [];
  const observers = [];
  let sandbox;
  let server;
  let cleanup;
  let models;

  const close = () => {
    if (cleanup) return cleanup;
    cleanup = (async () => {
      const failures = [];
      let dbResult;
      const release = async (label, operation) => {
        try { await operation(); } catch { failures.push(label); }
      };
      try {
        await release('HTTP listener', async () => {
          if (server?.listening) {
            server.closeAllConnections();
            await bounded(new Promise((resolve, reject) => server.close(error => error ? reject(error) : resolve())), 'HTTP listener');
          }
          assert.equal(server?.listening ?? false, false);
          if (server) assert.equal(server.address(), null);
        });
        await release('owned MongoDB database/connection', async () => { dbResult = await database.dispose(); });
        await release('Winston files', async () => {
          try {
            await bounded(Promise.all(opened), 'log opening');
          } finally {
            // Opening failures must still close every allocated logger/stream.
            const closed = loggers.flatMap(logger => logger.transports.map(transport => once(transport, 'closed')));
            loggers.forEach(logger => logger.close());
            await bounded(Promise.all([...closed, ...fileClosures]), 'log closing');
          }
          streams.forEach(stream => assert.equal(stream.closed, true));
          for (const filename of sandbox ? fs.readdirSync(sandbox) : []) {
            // Test-owned loggers are silent: no tokens, headers or financial bodies
            // may reach disk. Production logging policy is not changed or audited.
            assert.equal(fs.statSync(path.join(sandbox, filename)).size, 0, 'Integration logs must remain empty');
          }
        });
      } finally {
        // Also try to close loggers when an earlier open/close assertion failed.
        loggers.forEach(logger => logger.close());
        observers.reverse().forEach(observer => observer.mock.restore());
        for (const name of names) {
          if (savedEnv[name] === undefined) delete process.env[name];
          else process.env[name] = savedEnv[name];
        }
        await release('process context', async () => {
          for (const name of names) assert.ok(process.env[name] === savedEnv[name], 'Environment restoration failed');
          process.chdir(originalCwd);
          assert.equal(process.cwd(), originalCwd);
        });
        if (sandbox) {
          await release('temporary log directory', async () => {
            fs.rmSync(sandbox, { recursive: true, force: true });
            assert.equal(fs.existsSync(sandbox), false);
          });
        }
      }
      if (failures.length) throw new Error(`Integration cleanup failed: ${failures.join(', ')}`);
      return { ...dbResult, listenerClosed: true, logsClosed: true, directoryRemoved: true, environmentRestored: true };
    })();
    return cleanup;
  };

  try {
    sandbox = fs.mkdtempSync(path.join(os.tmpdir(), 'budget-mongodb-ownership-'));
    process.chdir(sandbox); // Includes isolation from the application's .env file.
    process.env.NODE_ENV = 'test';
    delete process.env.JWT_SECRET;
    process.env.DEFAULT_ALLOWED_METHODS = 'GET,POST,PATCH,DELETE,OPTIONS';
    const winston = require('winston');
    const createLogger = winston.createLogger;
    observers.push(mock.method(winston, 'createLogger', function (...args) {
      const logger = Reflect.apply(createLogger, this, args);
      logger.silent = true; // Only these test-owned loggers, before any HTTP request.
      loggers.push(logger);
      for (const transport of logger.transports) opened.push(once(transport, 'open'));
      return logger;
    }));
    const createWriteStream = fs.createWriteStream;
    observers.push(mock.method(fs, 'createWriteStream', function (...args) {
      const stream = Reflect.apply(createWriteStream, this, args);
      streams.push(stream);
      fileClosures.push(once(stream, 'close'));
      return stream;
    }));
    const load = Module._load;
    const bootstrapGuard = mock.method(Module, '_load', function (request, parent, ...args) {
      assert.notEqual(Module._resolveFilename(request, parent), compiled('server.js'), 'Production bootstrap is forbidden');
      return Reflect.apply(load, this, [request, parent, ...args]);
    });
    const importListenerGuard = mock.method(net.Server.prototype, 'listen', () => {
      throw new Error('Import-time listener is forbidden');
    });
    let app;
    try { app = require(compiled('app.js')); } finally {
      importListenerGuard.mock.restore(); bootstrapGuard.mock.restore();
    }
    assert.equal(require.cache[compiled('server.js')], undefined);
    assertOwnedDatabase(mongoose.connection, database.name);
    models = { expenses: require(compiled('models/expense.js')), incomes: require(compiled('models/income.js')) };
    await bounded(Promise.all(opened), 'log opening');
    server = app.listen(0, '127.0.0.1');
    await bounded(once(server, 'listening'), 'HTTP startup');
    assert.equal(server.address().address, '127.0.0.1');
  } catch {
    await close();
    throw new Error('MongoDB integration application setup failed; test resources released; details suppressed');
  }

  const request = (method, endpoint, body, token) => new Promise((resolve, reject) => {
    assert.equal(server.listening, true, 'Owned HTTP listener is closed');
    const req = http.request({ hostname: '127.0.0.1', port: server.address().port,
      method, path: endpoint, headers: { Connection: 'close', 'Content-Type': 'application/json',
        ...(token === undefined ? {} : { Authorization: `Bearer ${token}` }) } }, res => {
      let text = '';
      res.setEncoding('utf8');
      res.on('data', chunk => { text += chunk; });
      res.on('error', () => reject(new Error('Owned HTTP response failed')));
      res.on('end', () => {
        try { resolve({ status: res.statusCode, text, body: text ? JSON.parse(text) : undefined, contentType: res.headers['content-type'] }); }
        catch { reject(new Error('Owned HTTP response was not valid JSON')); }
      });
    });
    req.setTimeout(5000, () => req.destroy(new Error('Owned HTTP request timed out')));
    req.on('error', () => reject(new Error('Owned loopback HTTP request failed')));
    req.end(body === undefined ? undefined : JSON.stringify(body));
  });
  return { databaseName: database.name, mongoose, models, request, close,
    assertDatabase: () => assertOwnedDatabase(mongoose.connection, database.name) };
}

module.exports = { testConfiguration, assertOwnedDatabase, openTestDatabase, createHarness };
